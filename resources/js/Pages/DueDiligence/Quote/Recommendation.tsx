import { useState } from 'react';
import { router } from '@inertiajs/react';
import { CalendarClock, Clock, Database, Eye, FileText, Radar, XCircle } from 'lucide-react';
import { Button } from '@/Components/ui/Button';
import QuoteShell from '@/Components/DueDiligence/QuoteShell';
import DdIcon from '@/Components/DueDiligence/DdIcon';
import { Card, SampleBanner, Ticks, rand, usd } from '@/Components/DueDiligence/Ui';
import type { DdQuotePageProps, DdSku } from '@/types/due-diligence';

interface Props extends DdQuotePageProps {
    recommendation: { sku: DdSku | null; tier: string; score: number; reasons: string[]; assumptions: { label: string; value: string }[] };
}

/** DD-022 Due Diligence Service Recommendation (rule-based, human assistance available). */
export default function Recommendation(props: Props) {
    const { quote, sku, family, recommendation: rec } = props;
    const [busy, setBusy] = useState(false);
    const recSku = rec.sku ?? sku;
    const differs = recSku.code !== sku.code;
    const decide = (choice: 'accept' | 'keep') => {
        setBusy(true);
        router.post(`/due-diligence/quotes/${quote.reference}/recommendation`, { choice }, { onFinish: () => setBusy(false) });
    };
    const notIncluded = ['On-Site Physical Verification', 'Forensic Document Review', 'ESG Deep Dive Assessment', 'Continuous Monitoring Service', 'Custom Modelling / Scenario Analysis'].filter((x) => !(quote.addons ?? []).some((a) => x.toLowerCase().includes(a.replace('DD-ADD-', '').toLowerCase())));

    return (
        <QuoteShell
            page={props}
            title="Due Diligence Service Recommendation"
            subtitle="Our AI and specialist panel recommend the optimal package for your needs."
            description="Review the recommendation, included modules, assumptions and pricing before you accept."
            current={1}
            publicStage="1 Product or Proposal"
            priceTitle="Current price summary (ex VAT)"
            next="Once you accept this recommendation, you can proceed to the itemised fee manifest."
            aside={
                <>
                    <Button type="button" size="lg" className="w-full" trailingIcon="arrow-right" disabled={busy} onClick={() => decide('accept')}>{differs ? `Accept ${recSku.name}` : 'Continue / Accept Scope'}</Button>
                    {differs && <Button type="button" variant="outline" className="w-full" disabled={busy} onClick={() => decide('keep')}>Keep {sku.name}</Button>}
                </>
            }
        >
            <SampleBanner title={`Recommendation for ${String(quote.inputs.subject_name ?? 'your subject')} (${String(quote.inputs.jurisdiction ?? 'South Africa')})`} note="This recommendation is generated by transparent scoring rules from your answers and does not constitute a finding." sample={false} />
            <div className="grid gap-5 xl:grid-cols-12">
                <div className="overflow-hidden rounded-[10px] border border-parchment-400 bg-white xl:col-span-4">
                    <p className="bg-ink-950 py-2 text-center text-sm font-semibold text-parchment-100">Recommended Package</p>
                    <div className="p-4">
                        <div className="flex items-start gap-3">
                            <DdIcon name={family.icon} className="size-10 text-gold-700" />
                            <div>
                                <p className="text-lg font-bold">{recSku.name}</p>
                                <p className="font-mono text-xs text-ink-500">{recSku.code}</p>
                                <span className="mt-1 inline-block rounded bg-verified-50 px-2 py-0.5 text-[0.6875rem] font-semibold text-verified-700">Recommended · {rec.tier}</span>
                            </div>
                        </div>
                        <p className="mt-3 text-sm text-ink-600">Best balance of depth, speed and risk coverage for your {String(quote.inputs.purpose ?? 'decision').toLowerCase()}.</p>
                        <div className="mt-3 rounded-[8px] border border-gold-400 bg-gold-50 p-3 text-center">
                            <p className="text-xs text-ink-600">Board-Provisional Price (ex VAT)</p>
                            <p className="text-2xl font-bold">{rand((recSku.expert ?? 0) + (recSku.platform ?? 0), 2)}</p>
                            <p className="text-xs text-ink-500">{usd((recSku.expert ?? 0) + (recSku.platform ?? 0))}</p>
                        </div>
                        <dl className="mt-3 space-y-2 text-[0.8125rem]">
                            {[[Eye, 'Review Level', recSku.reviewLevel], [Clock, 'Target Turnaround', recSku.timeline], [CalendarClock, 'Access Period', '90 days from delivery'], [Database, 'Data Retention', '12 months (then purged)'], [Radar, 'Monitoring', 'Not included in this package']].map(([I, k, v]) => {
                                const Icon = I as typeof Eye;
                                return <div key={k as string} className="flex items-center gap-2"><Icon className="size-4 text-gold-600" aria-hidden="true" /><dt className="flex-1 text-ink-500">{k as string}</dt><dd className="font-medium">{v as string}</dd></div>;
                            })}
                        </dl>
                    </div>
                </div>
                <div className="space-y-4 xl:col-span-8">
                    <Card title="Why this fits"><Ticks items={rec.reasons} /></Card>
                    <div className="grid gap-4 md:grid-cols-3">
                        <Card title="Included Modules"><Ticks items={recSku.included.split(/,\s*(?![^()]*\))/).map((x) => x.replace(/\.$/, '').replace(/^and /, ''))} /></Card>
                        <Card title="Not Included (Exclusions)">
                            <ul className="space-y-1.5">{notIncluded.map((t) => <li key={t} className="flex gap-2 text-[0.8125rem]"><XCircle className="mt-0.5 size-4 shrink-0 text-risk-500" aria-hidden="true" />{t}</li>)}</ul>
                        </Card>
                        <Card title="Evidence You Need">
                            <ul className="space-y-1.5">
                                {(quote.inputs.subject_type === 'individual'
                                    ? ['Government-issued ID', 'Proof of Address', 'Signed Subject Consent', 'CV / Employment History']
                                    : ['Certificate of Incorporation', 'Shareholder Register', 'Directors and UBO Details', 'Financial Statements (latest)', 'Business Overview & Operations', 'Government-issued ID (signatories)']
                                ).map((t) => <li key={t} className="flex gap-2 text-[0.8125rem]"><FileText className="mt-0.5 size-4 shrink-0 text-gold-600" aria-hidden="true" />{t}</li>)}
                            </ul>
                        </Card>
                    </div>
                    <Card title="Key Assumptions">
                        <dl className="grid gap-x-6 gap-y-1 text-[0.8125rem] sm:grid-cols-2">
                            {rec.assumptions.map((a) => <div key={a.label}><dt className="inline text-ink-500">{a.label}: </dt><dd className="inline font-medium">{a.value}</dd></div>)}
                        </dl>
                    </Card>
                </div>
            </div>
        </QuoteShell>
    );
}
