import { Link, router } from '@inertiajs/react';
import * as L from 'lucide-react';
import { useState } from 'react';
import { BtnLink, Ico, btnClass } from '@/Components/Webinars/kit';
import { AiDisclosure, BASE, Box, ConfidenceRing, KpPage, VoiceBadge, type KpAnswerT, type KpShared } from '@/Components/Kp/kit';
import { cn } from '@/lib/cn';

interface Props extends KpShared {
    answer: KpAnswerT;
    followUps: string[];
    levels: { key: string; label: string; body: string; icon: string }[];
    recent: { reference: string; question: string; status: string }[];
}

const BANNER: Record<string, [string, string, string]> = {
    abstained: ['circle-alert', 'Not enough evidence to answer', 'border-attested-500/40 bg-attested-50'],
    routed: ['scale', 'This needs a qualified professional', 'border-controlled-500/40 bg-controlled-50'],
    declined: ['user-x', 'The assistant cannot speak as Kruger Phiri', 'border-risk-500/40 bg-risk-50'],
};

/** KP-SCR-019 AI Answer. */
export default function Answer({ screen, kpNav, answer: a, followUps, levels }: Props) {
    const [copied, setCopied] = useState(false);
    const [report, setReport] = useState(false);
    const [note, setNote] = useState('');
    const send = (rating: string, extra: Record<string, string> = {}) => router.post(`${BASE}/ask/${a.reference}/feedback`, { rating, ...extra }, { preserveScroll: true });
    const answered = a.status === 'answered';

    return (
        <KpPage
            screen={screen}
            kpNav={kpNav}
            accent="purple"
            crumbs={[['KP Knowledge Assistant', `${BASE}/ask`], ['AI Answer']]}
            title="AI Answer"
            badge={answered ? <span className="inline-flex items-center gap-1 rounded-full border border-verified-500/40 bg-verified-50 px-2 py-0.5 font-sans text-[0.75rem] font-semibold text-verified-700"><L.BadgeCheck className="size-3.5" />Cited</span> : null}
            intro={`Generated by KP Knowledge Assistant | ${a.asked} | Reference ${a.reference}`}
            actions={
                <>
                    <button type="button" onClick={() => { void navigator.clipboard?.writeText(window.location.href); setCopied(true); }} className={btnClass('outline', 'sm')}><L.Share2 className="size-3.5" />{copied ? 'Link copied' : 'Share'}</button>
                    <a href={`${BASE}/ask/${a.reference}/export`} className={btnClass('outline', 'sm')}><L.Download className="size-3.5" />Export</a>
                </>
            }
            left={
                <div className="space-y-4">
                    <Box title="Your Question" tone="cream"><p className="rounded-[8px] bg-white p-2 text-[0.8125rem] text-ink-900">{a.question}</p><p className="mt-1 text-[0.6875rem] text-ink-500">Asked {a.asked}</p></Box>
                    <Box title="Query Context">
                        <dl className="space-y-2 text-[0.75rem]">
                            <div><dt className="text-ink-500">Topic</dt><dd className="font-semibold text-ink-900">{a.topic ?? 'Not matched'}</dd></div>
                            <div><dt className="text-ink-500">Content types</dt><dd className="font-semibold text-ink-900">Insights, frameworks, resources</dd></div>
                            <div><dt className="text-ink-500">Sources</dt><dd className="font-semibold text-ink-900">Approved register content only</dd></div>
                        </dl>
                    </Box>
                    <Box title="Confidence Score">
                        <ConfidenceRing value={a.confidence} label={a.confidenceLabel} />
                        <p className="mt-2 text-[0.6875rem] text-ink-600">{answered ? 'Based on the evidence status of the cited sources: full texts score higher than titles or design excerpts.' : 'No score: the assistant did not answer from evidence.'}</p>
                        <Link href={`${BASE}/ask/${a.reference}/sources`} className="mt-2 inline-block text-[0.75rem] font-semibold text-gold-700">How we score confidence</Link>
                    </Box>
                </div>
            }
            rail={
                <>
                    {a.sources.length > 0 && (
                        <Box title={`Key Sources (${a.sources.length})`} icon="file-text">
                            <ol className="space-y-2.5">{a.sources.map((s) => <li key={s.n} className="flex gap-2 text-[0.75rem]"><span className="font-bold text-referenced-500">[{s.n}]</span><span><Link href={s.href} className="block font-semibold text-ink-900 hover:text-gold-700">{s.title}</Link><span className="text-ink-500">{s.typeLabel} | {s.evidence}</span></span></li>)}</ol>
                            <Link href={`${BASE}/ask/${a.reference}/sources`} className="mt-3 inline-flex items-center gap-1 text-[0.75rem] font-semibold text-gold-700">View all sources and confidence <L.ArrowRight className="size-3" /></Link>
                        </Box>
                    )}
                    <Box title="Next Steps" icon="arrow-right">
                        <ul className="space-y-1.5 text-[0.8125rem]">
                            {a.answer.hasLevels && <li><Link href={`${BASE}/explain?topic=${a.knowledgeKey}`} className="hover:text-gold-700">Explain this at my level</Link></li>}
                            <li><Link href={`${BASE}/action-pack/the-real-problem-isnt-capital`} className="hover:text-gold-700">Create an action plan</Link></li>
                            <li><Link href={`${BASE}/resources`} className="hover:text-gold-700">Find related resources</Link></li>
                            <li><Link href={`${BASE}/corrections`} className="hover:text-gold-700">See the corrections log</Link></li>
                        </ul>
                    </Box>
                    <Box title="Ask a Follow-up">
                        <ul className="space-y-1.5">{followUps.map((q) => <li key={q}><button type="button" onClick={() => router.post(`${BASE}/ask`, { question: q })} className="text-left text-[0.75rem] hover:text-gold-700">{q}</button></li>)}</ul>
                    </Box>
                </>
            }
        >
            <section className="rounded-[12px] border border-parchment-400 bg-white p-5">
                <header className="flex items-center gap-3">
                    <span className="flex size-11 items-center justify-center rounded-full bg-referenced-500 text-white"><L.Bot className="size-5" aria-hidden="true" /></span>
                    <div>
                        <h2 className="flex items-center gap-2 font-serif text-[1.125rem] font-bold text-ink-900">KP Knowledge Assistant Answer <VoiceBadge code="A" /></h2>
                        <p className="text-[0.75rem] text-ink-500">Based on approved insights from Kruger Phiri and The Business Clinic.Africa.</p>
                    </div>
                </header>

                {!answered && BANNER[a.status] && (
                    <div className={cn('mt-4 flex gap-3 rounded-[10px] border p-4', BANNER[a.status][2])}>
                        <Ico name={BANNER[a.status][0]} className="size-5 shrink-0" />
                        <p className="text-[0.8125rem] font-bold text-ink-900">{BANNER[a.status][1]}</p>
                    </div>
                )}

                <p className="mt-4 text-[0.9375rem] text-ink-800">{a.answer.intro}</p>
                {a.answer.points.length > 0 && (
                    <ol className="mt-3 divide-y divide-parchment-300 rounded-[10px] border border-parchment-400">
                        {a.answer.points.map((p, i) => (
                            <li key={p.title} className="flex items-start gap-3 p-3">
                                <span className="flex size-7 shrink-0 items-center justify-center rounded-full bg-ink-900 text-[0.75rem] font-bold text-parchment-50">{i + 1}</span>
                                <Ico name={p.icon} className="mt-0.5 size-5 shrink-0 text-gold-600" />
                                <span><span className="block text-[0.875rem] font-bold text-ink-900">{p.title}: {p.line}</span>{p.detail && <span className="block text-[0.8125rem] text-ink-600">{p.detail}</span>}</span>
                            </li>
                        ))}
                    </ol>
                )}
                {a.answer.close && <p className="mt-3 flex gap-2 rounded-[10px] border border-verified-500/30 bg-verified-50 p-3 text-[0.8125rem] text-ink-700"><L.ShieldCheck className="size-5 shrink-0 text-verified-500" aria-hidden="true" />{a.answer.close}</p>}

                {a.answer.related.length > 0 && (
                    <div className="mt-4">
                        <p className="text-[0.8125rem] font-bold text-ink-900">{answered ? 'Read more' : 'Closest published material'}</p>
                        <ul className="mt-1 space-y-1">{a.answer.related.map((r) => <li key={r.href + r.title}><Link href={r.href} className="text-[0.8125rem] text-gold-700 hover:underline">{r.title}</Link> <span className="text-[0.6875rem] text-ink-500">({r.kind})</span></li>)}</ul>
                    </div>
                )}
                {a.answer.route && <BtnLink href={a.answer.route[1]} className="mt-4" icon="arrow-right">{a.answer.route[0]}</BtnLink>}

                <div className="mt-5 flex flex-wrap items-center gap-2 border-t border-parchment-300 pt-4 text-[0.8125rem]">
                    <span className="text-ink-600">Was this answer helpful?</span>
                    <button type="button" aria-pressed={a.feedback === 'helpful'} onClick={() => send('helpful')} className={cn(btnClass('outline', 'sm'), a.feedback === 'helpful' && 'bg-verified-50')}><L.ThumbsUp className="size-3.5" />Yes</button>
                    <button type="button" aria-pressed={a.feedback === 'not-helpful'} onClick={() => send('not-helpful')} className={cn(btnClass('outline', 'sm'), a.feedback === 'not-helpful' && 'bg-attested-50')}><L.ThumbsDown className="size-3.5" />No</button>
                    <button type="button" onClick={() => setReport(!report)} className="ml-auto text-[0.75rem] font-semibold text-gold-700">Report a problem</button>
                </div>
                {report && (
                    <form className="mt-3 flex flex-col gap-2 sm:flex-row" onSubmit={(e) => { e.preventDefault(); send('report', { note }); setReport(false); }}>
                        <label htmlFor="note" className="sr-only">What is wrong?</label>
                        <input id="note" value={note} onChange={(e) => setNote(e.target.value)} maxLength={500} placeholder="What is wrong or out of date?" className="h-9 flex-1 rounded-[6px] border border-parchment-500 px-2 text-[0.8125rem]" />
                        <button type="submit" className={btnClass('dark', 'sm')}>Send to corrections desk</button>
                    </form>
                )}
                <AiDisclosure className="mt-4" />
            </section>

            {answered && levels.length > 0 && a.answer.hasLevels && (
                <Box title="Explain It at My Level" icon="lightbulb" tone="purple">
                    <ul className="flex flex-wrap gap-2">{levels.map((l) => <li key={l.key}><Link href={`${BASE}/explain?topic=${a.knowledgeKey}&level=${l.key}`} className="inline-flex items-center gap-1.5 rounded-full border border-referenced-500/40 bg-white px-3 py-1 text-[0.75rem] font-semibold text-referenced-500"><Ico name={l.icon} className="size-3.5" />{l.label}</Link></li>)}</ul>
                </Box>
            )}
        </KpPage>
    );
}
